/// `json_text` — Python's `str(v)` for the scalar kinds the AST can carry.
pub fn json_text(v: &Value) -> String {
    match v {
        Value::Null => String::new(),
        Value::Bool(b) => if *b { "True".to_string() } else { "False".to_string() },
        Value::Number(n) => n.to_string(),
        Value::String(s) => s.clone(),
        other => other.to_string(),
    }
}

/// `style['a']['b']` without the `KeyError`: the authority only ever reaches
/// keys `styles.sanitize` guarantees, so a miss here means the caller passed an
/// unsanitised dict.  Returning `Null` keeps the port total and lets each
/// accessor apply the documented `DEFAULT_STYLE` fallback.
pub fn dig<'a>(v: &'a Value, path: &[&str]) -> &'a Value {
    let mut cur = v;
    for k in path {
        match cur.get(*k) {
            Some(n) => cur = n,
            None => return &Value::Null,
        }
    }
    cur
}

/// `_TA.get(name, default)` for a style field that may be absent.
pub fn ta_of(v: &Value, default: i64) -> i64 {
    match v {
        Value::String(s) => ta_get(s).unwrap_or(default),
        _ => default,
    }
}

/// `bool(v.get(k, default))`.
pub fn bool_or(v: &Value, default: bool) -> bool {
    match v {
        Value::Bool(b) => *b,
        Value::Null => default,
        Value::Number(n) => n.as_f64().map(|f| f != 0.0).unwrap_or(default),
        Value::String(s) => !s.is_empty(),
        Value::Array(a) => !a.is_empty(),
        Value::Object(o) => !o.is_empty(),
    }
}

