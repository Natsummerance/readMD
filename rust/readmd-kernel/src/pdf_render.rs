    #[test]
    fn list_and_quote_flowables_carry_the_right_glyphs() {
        let style = style_for(json!({}));
        let st = Styles::build(&style, "MicrosoftYaHei");
        let mut warns = Vec::new();
        let story = build_story(
            &Value::Array(doc_simple()),
            &style,
            "T:/tmp",
            &no_image,
            &st,
            "MicrosoftYaHei",
            &DocGeometry::from_style(&style),
            &mut warns,
            &[],
        );
        let flat: Vec<String> = story
            .iter()
            .filter_map(|f| match f {
                Flowable::Paragraph { runs, .. } => Some(runs_plain_text(runs)),
                // the quote is a Table (`:424-437`), so its text lives in cells
                Flowable::Table(tf) => Some(
                    tf.rows
                        .iter()
                        .map(|r| {
                            r.iter()
                                .map(|c| runs_plain_text(&c.runs))
                                .collect::<Vec<_>>()
                                .join(" | ")
                        })
                        .collect::<Vec<_>>()
                        .join(" / "),
                ),
                _ => None,
            })
            .collect();
        assert_eq!(flat[0], "Alpha Title");
        assert!(flat.iter().any(|s| s == "• first bullet"), "{flat:?}");
        assert!(flat.iter().any(|s| s == "3. one"));
        assert!(flat.iter().any(|s| s == "4. two"));
        assert!(flat.iter().any(|s| s == "A quoted line. Second quoted line."));
        assert!(story.iter().any(|f| matches!(f, Flowable::Table(_))));
        assert!(story.iter().any(|f| matches!(f, Flowable::Rule { .. })));
        assert!(story.iter().any(
            |f| matches!(f, Flowable::Preformatted { lines, .. } if lines.len() == 2)
        ));
        assert_eq!(warns, Vec::<String>::new());
    }

