/// `os.path.exists(os.path.join(WINDIR, 'Fonts', candidates[selected]))`
/// (`:224-225`) — the existence test behind `_font_ready` for the five names
/// `render()` is willing to promote to the body font.
pub fn font_file_present(file: &str) -> bool {
    let windir = std::env::var("WINDIR").unwrap_or_else(|_| "C:/Windows".to_string());
    let a = std::path::Path::new(&windir).join("Fonts").join(file);
    if a.exists() {
        return true;
    }
    std::path::Path::new("C:/Windows/Fonts").join(file).exists()
}

/// Everything `render()` produces before writing the file: the laid-out pages,
/// the outline/TOC records and the geometry they were laid out in.
pub fn build(
    blocks: &Value,
    style: &Value,
    tmpdir: &str,
    resolve: &dyn Fn(&str) -> Option<String>,
    warns: &mut Vec<String>,
) -> Result<RenderedDoc, PdfError> {
    // ---- font selection (`:219-228`)
    let mut font = register_fonts();
    let selected = json_text(dig(style, &["typography", "font"]));
    if let Some((_, file)) = FONT_CANDIDATES.iter().find(|(k, _)| *k == selected) {
        let file = *file;
        if font_file_present(file) {
            note_registered(&selected);
            font = selected.clone();
        } else {
            warns.push(format!("所选字体不可用，已使用中文后备字体：{selected}"));
        }
    }

    // Embedded TrueType for everything WinAnsi cannot encode; ended below.
    crate::pdf_fonts::begin(&selected);
    struct EndFonts;
    impl Drop for EndFonts {
        fn drop(&mut self) {
            // Only reached on an early return; the normal path calls finish().
            let _ = crate::pdf_fonts::finish();
        }
    }
    let guard = EndFonts;

    let mut geom = DocGeometry::from_style(style);
    geom.body_font = font.clone();
    let st = Styles::build(style, &font);

    let mut base = ExportDoc::new();
    base.footer_text = json_text(dig(style, &["footer", "text"]));
    base.page_numbers = bool_or(dig(style, &["footer", "pageNumbers"]), true);
    base.header = style.get("header").cloned().unwrap_or(Value::Null);
    base.body_font = font.clone();

    // The story is built *once* — `render()` does too, which is why a warning
    // can never be duplicated by `multiBuild`'s extra passes.
    let mut story = build_story(blocks, style, tmpdir, resolve, &st, &font, &geom, warns, &[]);
    let toc_idx = story.iter().position(|f| matches!(f, Flowable::Toc(_)));
    let toc_on = toc_idx.is_some();

    let mut pages: Vec<RenderedPage> = Vec::new();
    let mut out_doc = base.clone();
    if !toc_on {
        out_doc = base.clone();
        pages = paginate(&story, &geom, &st, &mut out_doc);
    } else {
        let mut prev: Vec<(i64, String, i64)> = Vec::new();
        for _pass in 0..10usize {
            if let Some(i) = toc_idx {
                if let Flowable::Toc(ref mut v) = story[i] {
                    *v = prev
                        .iter()
                        .map(|(l, t, p)| TocEntry {
                            level: *l,
                            text: t.clone(),
                            page: *p,
                        })
                        .collect();
                }
            }
            let mut d = base.clone();
            let p = paginate(&story, &geom, &st, &mut d);
            let stable = {
                let cur = d.toc_entries.clone();
                cur.len() == prev.len()
                    && cur
                        .iter()
                        .zip(prev.iter())
                        .all(|(a, b)| a.0 == b.0 && a.1 == b.1 && a.2 == b.2)
            };
            pages = p;
            out_doc = d;
            prev = out_doc.toc_entries.clone();
            if stable {
                break;
            }
        }
    }

    std::mem::forget(guard);
    let (embedded, font_warns) = crate::pdf_fonts::finish();
    warns.extend(font_warns);
    Ok(RenderedDoc {
        geom,
        pages,
        outlines: out_doc.outlines.clone(),
        toc_entries: out_doc.toc_entries.clone(),
        producer_face: font,
        embedded,
    })
}

