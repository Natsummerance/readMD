    // `oracle.py` hands the *user* fragment to `pdf_render.render()`, which
    // deep-merges it over `styles.DEFAULT_STYLE`.  `style_float()` falls back to
    // 11.0 for a missing `headings.hN.size`, so a test that passed the raw
    // fragment would not be reproducing the oracle; these fixtures are the
    // merged dictionary the Python renderer actually sees.

    fn merge(base: &Value, over: &Value) -> Value {
        match (base, over) {
            (Value::Object(b), Value::Object(o)) => {
                let mut m = b.clone();
                for (k, v) in o {
                    let merged = match m.get(k) {
                        Some(bb) if bb.is_object() && v.is_object() => merge(bb, v),
                        _ => v.clone(),
                    };
                    m.insert(k.clone(), merged);
                }
                Value::Object(m)
            }
            (_, o) => o.clone(),
        }
    }

