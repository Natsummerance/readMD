/// `reportlab.lib.units.mm` (`from reportlab.lib.units import mm`, :12).
/// reportlab derives it as `inch/2.54/10` with `inch = 72.0`.
pub const MM: f64 = 72.0 / 2.54 / 10.0;

/// `_PAGE_MAP` (`:25`) — the `size` names reportlab's `pagesizes` can answer
/// directly.  Values are `(width, height)` in **points**, portrait order, which
/// is what `_PAGE_MAP` holds (`A4 = (595.2755905511812, 841.8897637795277)`).
pub fn page_map(size: &str) -> Option<(f64, f64)> {
    let mm = MM;
    match size {
        "A4" => Some((210.0 * mm, 297.0 * mm)),
        "A5" => Some((148.0 * mm, 210.0 * mm)),
        "B5" => Some((176.0 * mm, 250.0 * mm)),
        "Letter" => Some((215.9 * mm, 279.4 * mm)),
        "Legal" => Some((215.9 * mm, 355.6 * mm)),
        _ => None,
    }
}

/// `reportlab.lib.enums` alignment codes (`:9`, used through `_TA` at :26).
/// `TA_LEFT=0, TA_CENTER=1, TA_RIGHT=2, TA_JUSTIFY=4`.
pub const TA_LEFT: i64 = 0;
pub const TA_CENTER: i64 = 1;
pub const TA_RIGHT: i64 = 2;
pub const TA_JUSTIFY: i64 = 4;

/// `_TA` (`:26`) — `dict.get` semantics, so an unknown name is *absent*, and
/// every call site supplies its own default.
pub fn ta_get(name: &str) -> Option<i64> {
    match name {
        "left" => Some(TA_LEFT),
        "center" => Some(TA_CENTER),
        "right" => Some(TA_RIGHT),
        "justify" => Some(TA_JUSTIFY),
        _ => None,
    }
}

