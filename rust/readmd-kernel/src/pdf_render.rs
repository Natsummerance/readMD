/// `_first_existing(*paths)` (`:31-35`) — first hit wins, else the *first*
/// argument is returned even when it does not exist.
pub fn first_existing(paths: &[&str]) -> String {
    for p in paths {
        if std::path::Path::new(p).exists() {
            return (*p).to_string();
        }
    }
    paths.first().copied().unwrap_or("").to_string()
}

