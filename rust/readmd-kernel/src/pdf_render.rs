/// The four faces a reportlab `<b>`/`<i>`/`<font face>` combination can reach
/// inside a paragraph, plus the mono face `register_mono_fonts` chooses.
#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum FaceStyle {
    Regular,
    Bold,
    Italic,
    BoldItalic,
    Mono,
}

impl FaceStyle {
    /// `<b>` / `<i>` wrap the current face, so nesting composes: reportlab's
    /// paragraph parser resolves `<b><i>x</i></b>` to `Helvetica-BoldOblique`.
    pub fn with_bold(self) -> FaceStyle {
        match self {
            FaceStyle::Regular => FaceStyle::Bold,
            FaceStyle::Italic => FaceStyle::BoldItalic,
            other => other,
        }
    }

    pub fn with_italic(self) -> FaceStyle {
        match self {
            FaceStyle::Regular => FaceStyle::Italic,
            FaceStyle::Bold => FaceStyle::BoldItalic,
            other => other,
        }
    }

    /// The base-14 face for WinAnsi-representable text.
    pub fn face(self, base: Face) -> Face {
        match self {
            FaceStyle::Mono => match base {
                Face::CourierBold | Face::Courier => base,
                _ => Face::Courier,
            },
            FaceStyle::Regular => match base {
                Face::TimesBold => Face::TimesRoman,
                Face::HelveticaBold | Face::HelveticaBoldOblique => Face::Helvetica,
                f => f,
            },
            FaceStyle::Bold => match base {
                Face::Courier | Face::CourierBold => Face::CourierBold,
                Face::TimesRoman | Face::TimesBold => Face::TimesBold,
                _ => Face::HelveticaBold,
            },
            FaceStyle::Italic => match base {
                Face::Courier | Face::CourierBold => Face::CourierOblique,
                Face::TimesRoman | Face::TimesBold => Face::TimesItalic,
                _ => Face::HelveticaOblique,
            },
            FaceStyle::BoldItalic => match base {
                Face::Courier | Face::CourierBold => Face::CourierBoldOblique,
                Face::TimesRoman | Face::TimesBold => Face::TimesBoldItalic,
                _ => Face::HelveticaBoldOblique,
            },
        }
    }
}

/// One styled piece of an inline flow.  `Text` carries the string; `Image`
/// carries the geometry `_img_tag`/the `<img .../>` tag would have carried.
#[derive(Debug, Clone, PartialEq)]
pub enum RunContent {
    Text(String),
    Image(InlineImage),
}

#[derive(Debug, Clone, PartialEq)]
pub struct Run {
    pub content: RunContent,
    pub face: FaceStyle,
    pub size: f64,
    pub color: Rgb,
    /// `Some(href)` is what `<a href="..." color="...">` means: the text is
    /// drawn in `color` and gets a link annotation.
    pub href: Option<String>,
}

impl Run {
    pub fn text(&self) -> &str {
        match &self.content {
            RunContent::Text(s) => s,
            RunContent::Image(_) => "",
        }
    }
    pub fn is_image(&self) -> bool {
        matches!(&self.content, RunContent::Image(_))
    }
}

/// The per-paragraph context an inline walk needs: the face and colour the
/// surrounding markup has already established, and the body font name (which
/// decides whether `<i>`/`<b>` land on a real oblique/bold face or on the
/// plain one, exactly as `fontName=(font + '-Bold') if ... else font` does).
#[derive(Debug, Clone)]
pub struct InlineCtx {
    pub face: FaceStyle,
    pub color: Rgb,
    pub href: Option<String>,
    pub size: f64,
    pub base_face: Face,
}

/// `_inline_markup(nodes, style, tmpdir, resolve)` (`:131-168`).
pub fn inline_markup(
    nodes: &Value,
    style: &Value,
    tmpdir: &str,
    resolve: &dyn Fn(&str) -> Option<String>,
) -> Vec<Run> {
    let ctx = InlineCtx {
        face: FaceStyle::Regular,
        color: hex_d(dig(style, &["typography", "color"])),
        href: None,
        size: style_float(dig(style, &["typography", "size"]), 11.0),
        base_face: Face::Helvetica,
    };
    inline_markup_ctx(nodes, style, tmpdir, resolve, &ctx)
}

fn inline_markup_ctx(
    nodes: &Value,
    style: &Value,
    tmpdir: &str,
    resolve: &dyn Fn(&str) -> Option<String>,
    ctx: &InlineCtx,
) -> Vec<Run> {
    let mut out: Vec<Run> = Vec::new();
    let mono = register_mono_fonts();
    let mono_face = face_for_logical(&mono);
    // `code_size = max(6.0, float(style['code']['size']) - 0.5)`
    let code_size = (plain_float(dig(style, &["code", "size"]), 9.5) - 0.5).max(6.0);
    let link_color = hex(dig(style, &["link", "color"]), "#2b6cb0");
    let items: Vec<&Value> = match nodes {
        Value::Array(a) => a.iter().collect(),
        Value::Null => Vec::new(),
        other => vec![other],
    };
    for nd in items {
        let t = match nd.get("t").and_then(|v| v.as_str()) {
            Some(s) => s,
            None => continue,
        };
        match t {
            "text" => out.push(Run {
                content: RunContent::Text(json_text(nd.get("v").unwrap_or(&Value::Null))),
                face: ctx.face,
                size: ctx.size,
                color: ctx.color,
                href: ctx.href.clone(),
            }),
            "bold" | "italic" => {
                let mut sub = ctx.clone();
                sub.face = if t == "bold" { ctx.face.with_bold() } else { ctx.face.with_italic() };
                // `nd['v'] if isinstance(nd['v'], list) else _parser.parse_inline(nd['v'])`
                let inner = nd.get("v").cloned().unwrap_or(Value::Null);
                let inner = normalize_inline(&inner);
                out.extend(inline_markup_ctx(&inner, style, tmpdir, resolve, &sub));
            }
            "code" => {
                // `<font face="%s" size="%.1f" color="#c7254e">%s</font>`
                let mut sub = ctx.clone();
                sub.face = if mono == "Courier" { FaceStyle::Mono } else { FaceStyle::Mono };
                sub.base_face = mono_face;
                let body = json_text(nd.get("v").unwrap_or(&Value::Null));
                out.push(Run {
                    content: RunContent::Text(body),
                    face: FaceStyle::Mono,
                    size: code_size,
                    color: hex_parse("#c7254e").unwrap(),
                    href: ctx.href.clone(),
                });
            }
            "strike" => {
                // The authority emits *only* the escaped text here (:146-147) —
                // no `<strike>` tag — so a strikethrough is visually plain text.
                let v = nd.get("v").cloned().unwrap_or(Value::Null);
                let body = match &v {
                    Value::String(s) => s.clone(),
                    Value::Array(_) => inline_text(&v),
                    other => json_text(other),
                };
                out.push(Run {
                    content: RunContent::Text(body),
                    face: ctx.face,
                    size: ctx.size,
                    color: ctx.color,
                    href: ctx.href.clone(),
                });
            }
            "link" => {
                let href = json_text(nd.get("href").unwrap_or(&Value::Null));
                let mut sub = ctx.clone();
                sub.color = link_color;
                sub.href = Some(href);
                let inner = nd.get("text").cloned().unwrap_or(Value::Null);
                let inner = normalize_inline(&inner);
                out.extend(inline_markup_ctx(&inner, style, tmpdir, resolve, &sub));
            }
            "image" => {
                let src_key = json_text(nd.get("src").unwrap_or(&Value::Null));
                let src = resolve(&src_key);
                match src {
                    Some(p) => {
                        if let Some((iw, ih)) = image_size_path(&p) {
                            if ih > 0.0 {
                                // `base = float(style['typography']['size']) * 1.3`
                                let base = plain_float(dig(style, &["typography", "size"]), 11.0) * 1.3;
                                let scale = (base / ih).min(1.0);
                                out.push(Run {
                                    content: RunContent::Image(InlineImage {
                                        src: p.replace('\\', "/"),
                                        width: iw * scale,
                                        height: ih * scale,
                                        math: None,
                                    }),
                                    face: ctx.face,
                                    size: ctx.size,
                                    color: ctx.color,
                                    href: ctx.href.clone(),
                                });
                                continue;
                            }
                        }
                        // `except Exception:` -> `_esc(nd['alt'] or nd['src'])`
                        let alt = json_text(nd.get("alt").unwrap_or(&Value::Null));
                        let body = if alt.is_empty() { src_key } else { alt };
                        out.push(Run {
                            content: RunContent::Text(body),
                            face: ctx.face,
                            size: ctx.size,
                            color: ctx.color,
                            href: ctx.href.clone(),
                        });
                    }
                    // `if src:` false -> the node contributes nothing at all.
                    None => {}
                }
            }
            "math" => {
                let fallback = bool_or(nd.get("fallback").unwrap_or(&Value::Null), false);
                let latex = json_text(nd.get("latex").unwrap_or(&Value::Null));
                if let Some(f) = crate::math_layout::layout(&latex, false, ctx.size) {
                    out.push(Run {
                        content: RunContent::Image(InlineImage::formula(f)),
                        face: ctx.face,
                        size: ctx.size,
                        color: ctx.color,
                        href: ctx.href.clone(),
                    });
                } else if fallback {
                    out.push(Run {
                        content: RunContent::Text(json_text(nd.get("latex").unwrap_or(&Value::Null))),
                        face: ctx.face,
                        size: ctx.size,
                        color: ctx.color,
                        href: ctx.href.clone(),
                    });
                } else {
                    let png = nd.get("png").and_then(|v| match v {
                        Value::Array(a) => Some(a.iter().filter_map(|b| b.as_u64()).map(|b| b as u8).collect::<Vec<u8>>()),
                        _ => None,
                    });
                    let w = plain_float(nd.get("w").unwrap_or(&Value::Null), 0.0);
                    let h = plain_float(nd.get("h").unwrap_or(&Value::Null), 0.0);
                    if let Some(tag) = img_tag(tmpdir, png.as_deref(), w, h) {
                        out.push(Run {
                            content: RunContent::Image(tag),
                            face: ctx.face,
                            size: ctx.size,
                            color: ctx.color,
                            href: ctx.href.clone(),
                        });
                    }
                }
            }
            _ => {}
        }
    }
    out
}

/// `nd['v'] if isinstance(nd['v'], list) else _parser.parse_inline(nd['v'])` —
/// a bare string is the degenerate one-text-node case.  Re-parsing markdown
/// inline here would need the parser; the AST the port is fed always carries
/// lists, so a string degrades to a single `text` node.
fn normalize_inline(v: &Value) -> Value {
    match v {
        Value::Array(_) => v.clone(),
        Value::Null => Value::Array(Vec::new()),
        other => Value::Array(vec![serde_json::json!({ "t": "text", "v": json_text(other) })]),
    }
}

/// `_parser.inline_text(nodes)` — the recursive plain-text projection, which is
/// also what `Paragraph.getPlainText()` answers for the TOC/outline path.
pub fn inline_text(nodes: &Value) -> String {
    let mut s = String::new();
    match nodes {
        Value::Array(a) => {
            for nd in a {
                let t = nd.get("t").and_then(|v| v.as_str()).unwrap_or("");
                match t {
                    "text" | "code" | "math" => {
                        if t == "math" && !bool_or(nd.get("fallback").unwrap_or(&Value::Null), false) {
                            continue;
                        }
                        s.push_str(&json_text(nd.get("v").or(nd.get("latex")).unwrap_or(&Value::Null)));
                    }
                    "bold" | "italic" => s.push_str(&inline_text(&normalize_inline(nd.get("v").unwrap_or(&Value::Null)))),
                    "strike" => {
                        let v = nd.get("v").cloned().unwrap_or(Value::Null);
                        match &v {
                            Value::String(x) => s.push_str(x),
                            _ => s.push_str(&inline_text(&v)),
                        }
                    }
                    "link" => s.push_str(&inline_text(&normalize_inline(nd.get("text").unwrap_or(&Value::Null)))),
                    "image" => s.push_str(&json_text(nd.get("alt").unwrap_or(&Value::Null))),
                    _ => {}
                }
            }
        }
        Value::String(x) => s.push_str(x),
        _ => {}
    }
    s
}

/// Same, for the run stream a paragraph already holds.
pub fn runs_plain_text(runs: &[Run]) -> String {
    let mut s = String::new();
    for r in runs {
        match &r.content {
            RunContent::Text(t) => s.push_str(t),
            RunContent::Image(_) => {}
        }
    }
    s
}

