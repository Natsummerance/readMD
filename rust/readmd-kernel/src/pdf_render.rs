/// CPython's `repr(float)` / `str(float)` for the values this module produces:
/// shortest round-tripping decimal, scientific iff `decpt <= -4 || decpt > 16`,
/// `-0.0` preserved, `.0` suffix for integral values.
pub fn py_repr_float(x: f64) -> String {
    if x.is_nan() {
        return "nan".to_string();
    }
    if x.is_infinite() {
        return if x > 0.0 { "inf".to_string() } else { "-inf".to_string() };
    }
    if x == 0.0 {
        return if x.is_sign_negative() { "-0.0".to_string() } else { "0.0".to_string() };
    }
    let shortest = format!("{:e}", x);
    let (mant_e, exp_s) = shortest.split_once('e').unwrap_or(("0", "0"));
    let exp: i64 = exp_s.parse().unwrap_or(0);
    let neg = mant_e.starts_with('-');
    let digits: String = mant_e.chars().filter(|c| c.is_ascii_digit()).collect();
    let digits = digits.trim_end_matches('0');
    let digits = if digits.is_empty() { "0" } else { digits };
    // `decpt` is the number of digits before the decimal point.
    let decpt: i64 = exp + 1;
    let mut out = if decpt <= -4 || decpt > 16 {
        let m = if digits.len() <= 1 {
            digits.to_string()
        } else {
            format!("{}.{}", &digits[..1], &digits[1..])
        };
        let e = decpt - 1;
        format!("{m}e{}{:02}", if e < 0 { "-" } else { "+" }, e.abs())
    } else if decpt <= 0 {
        format!("0.{}{digits}", "0".repeat((-decpt) as usize))
    } else if (decpt as usize) >= digits.len() {
        format!("{}{}.0", digits, "0".repeat(decpt as usize - digits.len()))
    } else {
        let d = decpt as usize;
        format!("{}.{}", &digits[..d], &digits[d..])
    };
    if neg {
        out.insert(0, '-');
    }
    out
}

/// `reportlab.lib.utils.fp_str` — the formatter every content-stream number in
/// a reportlab PDF goes through: six-decimal fixed, trailing zeros and the
/// trailing point stripped, and a negative-but-not-representable value flushed
/// to zero.
pub fn fp_str(x: f64) -> String {
    if x < 0.0 && x > -1e-4 {
        return "0".to_string();
    }
    if x == x.trunc() && x.abs() < 1e15 {
        return format!("{}", x as i64);
    }
    let s = format!("{:.6}", x);
    let s = s.trim_end_matches('0');
    let s = s.trim_end_matches('.');
    if s.is_empty() || s == "-" {
        "0".to_string()
    } else {
        s.to_string()
    }
}

/// `'%d' % v` and `float(v or 11)` (`_size`, `:112-113`) — Python's `or` means
/// `0` and `null` and `""` all collapse to the default.
pub fn style_float(v: &Value, default: f64) -> f64 {
    match v {
        Value::Null => default,
        Value::Bool(b) => {
            if *b {
                1.0
            } else {
                default
            }
        }
        Value::Number(n) => {
            let f = n.as_f64().unwrap_or(0.0);
            if f == 0.0 {
                default
            } else {
                f
            }
        }
        Value::String(s) => match s.trim().parse::<f64>() {
            Ok(f) if f != 0.0 => f,
            _ => default,
        },
        _ => default,
    }
}

