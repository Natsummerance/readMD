/// `reportlab.lib.colors.HexColor` normalised to three `f64` channels.
#[derive(Debug, Clone, Copy, PartialEq)]
pub struct Rgb {
    pub r: f64,
    pub g: f64,
    pub b: f64,
}

impl Rgb {
    pub fn rgb(r: f64, g: f64, b: f64) -> Rgb {
        Rgb { r, g, b }
    }
    /// `color.hexval()` — `'0x%02x%02x%02x'`; `_inline_markup` slices it with
    /// `[2:]` (`:151`) to get the bare six digits for `<a color="...">`.
    pub fn hexval(&self) -> String {
        format!(
            "0x{:02x}{:02x}{:02x}",
            (self.r * 255.0).round() as i64,
            (self.g * 255.0).round() as i64,
            (self.b * 255.0).round() as i64
        )
    }
    pub fn hexval_tail(&self) -> String {
        let h = self.hexval();
        h.chars().skip(2).collect()
    }
    /// Content-stream colour operator for this colour.
    pub fn fill_op(&self) -> String {
        format!("{} {} {} rg\n", fp_str(self.r), fp_str(self.g), fp_str(self.b))
    }
    pub fn stroke_op(&self) -> String {
        format!("{} {} {} RG\n", fp_str(self.r), fp_str(self.g), fp_str(self.b))
    }
}

pub const WHITE: Rgb = Rgb { r: 1.0, g: 1.0, b: 1.0 };

/// `colors.HexColor('#999999')` and friends, spelled out once.
pub fn gray128() -> Rgb {
    Rgb::rgb(0.533_333_333_333_333_3, 0.533_333_333_333_333_3, 0.533_333_333_333_333_3)
}

/// `_hex(v, default='#000000')` (`:107-109`).
///
/// `re.match(r'^#([0-9a-fA-F]{6})$', v or '')` — a non-string or a malformed
/// string falls back to the default, and the default itself is *not* validated.
pub fn hex(v: &Value, default: &str) -> Rgb {
    let s = match v {
        Value::String(s) => s.clone(),
        Value::Null => String::new(),
        other => json_text(other),
    };
    match hex_parse(&s) {
        Some(c) => c,
        None => hex_parse(default).unwrap_or(Rgb::rgb(0.0, 0.0, 0.0)),
    }
}

/// The one-argument form used all over the module (`_hex('#111111')`).
pub fn hex_d(v: &Value) -> Rgb {
    hex(v, "#000000")
}

/// `^#([0-9a-fA-F]{6})$` with **no** `re.M`, so embedded newlines reject.
pub fn hex_parse(s: &str) -> Option<Rgb> {
    let t = s.trim_end();
    if t.len() != 7 || !t.starts_with('#') {
        return None;
    }
    let body = &t[1..];
    if !body.chars().all(|c| c.is_ascii_hexdigit()) {
        return None;
    }
    let n = u32::from_str_radix(body, 16).ok()?;
    Some(Rgb::rgb(
        ((n >> 16) & 0xff) as f64 / 255.0,
        ((n >> 8) & 0xff) as f64 / 255.0,
        (n & 0xff) as f64 / 255.0,
    ))
}

