/// `styles.page_dimensions(style)` (`styles.py:235-239`) in **mm**.
pub fn page_dimensions(style: &Value) -> (f64, f64) {
    let page = style.get("page").cloned().unwrap_or(Value::Null);
    let sizes: [(&str, (f64, f64)); 6] = [
        ("A3", (297.0, 420.0)),
        ("A4", (210.0, 297.0)),
        ("A5", (148.0, 210.0)),
        ("B5", (176.0, 250.0)),
        ("Letter", (215.9, 279.4)),
        ("Legal", (215.9, 355.6)),
    ];
    let size_name = match page.get("size") {
        Some(Value::String(s)) => s.clone(),
        _ => "A4".to_string(),
    };
    let orientation = match page.get("orientation") {
        Some(Value::String(s)) => s.clone(),
        _ => "portrait".to_string(),
    };
    let mut wh = if size_name == "Custom" {
        (
            plain_float(page.get("width").unwrap_or(&Value::Null), 210.0),
            plain_float(page.get("height").unwrap_or(&Value::Null), 297.0),
        )
    } else {
        match sizes.iter().find(|(k, _)| *k == size_name) {
            Some((_, v)) => *v,
            None => (210.0, 297.0),
        }
    };
    if orientation == "landscape" {
        wh = (wh.0.max(wh.1), wh.0.min(wh.1));
    }
    wh
}

/// The whole style-derived geometry `render()` computes before building the
/// story (`pdf_render.py:229-276`), kept together so the layout engine and the
/// tests see one struct instead of twelve positional lookups.
#[derive(Debug, Clone)]
pub struct DocGeometry {
    pub page_w: f64,
    pub page_h: f64,
    pub left: f64,
    pub right: f64,
    pub top: f64,
    pub bottom: f64,
    pub width: f64,
    pub height: f64,
    pub avail: f64,
    pub body_font: String,
    pub title: String,
    pub author: String,
    pub subject: String,
}

impl DocGeometry {
    /// `size = tuple(value * mm for value in page_dimensions(style))` plus the
    /// four `page[...] * mm` margins and `doc.width`/`doc.height`.
    pub fn from_style(style: &Value) -> DocGeometry {
        let (pw, ph) = page_dimensions(style);
        let page = style.get("page").cloned().unwrap_or(Value::Null);
        let left = plain_float(page.get("marginLeft").unwrap_or(&Value::Null), 18.0) * MM;
        let right = plain_float(page.get("marginRight").unwrap_or(&Value::Null), 18.0) * MM;
        let top = plain_float(page.get("marginTop").unwrap_or(&Value::Null), 20.0) * MM;
        let bottom = plain_float(page.get("marginBottom").unwrap_or(&Value::Null), 20.0) * MM;
        let width = pw * MM - left - right;
        let height = ph * MM - top - bottom;
        let g = DocGeometry {
            page_w: pw * MM,
            page_h: ph * MM,
            left,
            right,
            top,
            bottom,
            width,
            height,
            avail: width - 12.0,
            body_font: "Helvetica".to_string(),
            title: meta_text(style, "title"),
            author: meta_text(style, "author"),
            subject: meta_text(style, "subject"),
        };
        g
    }
}

/// `style['meta'].get('title') or ''` — sanitised to a `[:120]` string by
/// `styles.sanitize`, so a non-string can only arrive from an unsanitised dict.
pub fn meta_text(style: &Value, key: &str) -> String {
    match dig(style, &["meta", key]) {
        Value::Null => String::new(),
        v => json_text(v),
    }
}

/// The `body_style` / `head_styles` / `li_style` / `code_style` / `quote_style`
/// block (`:250-276`).
#[derive(Debug, Clone)]
pub struct Styles {
    pub body: PStyle,
    pub head: [PStyle; 6],
    pub li: PStyle,
    pub code: PStyle,
    pub quote: PStyle,
    pub code_flow: PStyle,
    /// `toc.levelStyles` (`:303-310`).
    pub toc_levels: Vec<PStyle>,
    /// `ParagraphStyle('TocTitle', …)` (`:311-312`).
    pub toc_title: PStyle,
}

impl Styles {
    pub fn build(style: &Value, font: &str) -> Styles {
        let ty = style.get("typography").cloned().unwrap_or(Value::Null);
        let ty_size = style_float(ty.get("size").unwrap_or(&Value::Null), 11.0);
        let line_height = plain_float(ty.get("lineHeight").unwrap_or(&Value::Null), 1.6);
        let mut body = PStyle::base(
            font,
            ty_size,
            ty_size * line_height,
        );
        body.space_after = plain_float(ty.get("spacing").unwrap_or(&Value::Null), 6.0);
        body.color = hex_d(ty.get("color").unwrap_or(&Value::Null));
        body.align = ta_of(ty.get("align").unwrap_or(&Value::Null), TA_LEFT);
        body.first_line_indent =
            plain_float(ty.get("firstLineIndent").unwrap_or(&Value::Null), 0.0) * MM;

        let mut head: [PStyle; 6] = [
            body.clone(),
            body.clone(),
            body.clone(),
            body.clone(),
            body.clone(),
            body.clone(),
        ];
        for i in 0..6usize {
            let key = format!("h{}", i + 1);
            let h = dig(style, &["headings", key.as_str()]).clone();
            let hs = style_float(h.get("size").unwrap_or(&Value::Null), 11.0);
            let mut st = PStyle::child(&body, &format!("H{}", i + 1));
            st.size = hs;
            st.leading = hs * 1.35;
            st.space_before = plain_float(h.get("before").unwrap_or(&Value::Null), 10.0);
            st.space_after = plain_float(h.get("after").unwrap_or(&Value::Null), 6.0);
            st.color = hex_d(h.get("color").unwrap_or(&Value::Null));
            st.align = ta_of(h.get("align").unwrap_or(&Value::Null), TA_LEFT);
            st.first_line_indent = 0.0;
            st.keep_with_next = true;
            // `fontName=(font + '-Bold') if (h['bold'] and (font + '-Bold') in
            // getRegisteredFontNames()) else font`
            let bold_wanted = bool_or(h.get("bold").unwrap_or(&Value::Null), true);
            let want = format!("{font}-Bold");
            let use_bold = bold_wanted && font_ready(&want);
            st.face = if use_bold { FaceStyle::Bold } else { FaceStyle::Regular };
            st.font_name = if use_bold { want } else { font.to_string() };
            head[i] = st;
        }

        let mut li = PStyle::child(&body, "Li");
        li.left_indent = 18.0;
        li.first_line_indent = 0.0;

        let mono = register_mono_fonts();
        let mut code = PStyle::base(&mono, plain_float(dig(style, &["code", "size"]), 9.5), 0.0);
        code.name = "Code".to_string();
        code.leading = code.size * 1.4;
        code.color = hex_d(dig(style, &["code", "color"]));
        code.align = TA_LEFT;
        code.face = FaceStyle::Mono;

        let quote = PStyle {
            color: hex_d(dig(style, &["quote", "color"])),
            ..PStyle::child(&body, "Quote")
        };

        let code_flow = PStyle {
            name: "CodeFlow".to_string(),
            back_color: Some(hex_d(dig(style, &["code", "bg"]))),
            border_padding: 8.0,
            space_after: 10.0,
            ..code.clone()
        };

        // `toc.levelStyles = [ParagraphStyle('T1', …), …, ParagraphStyle('T6', …)]`
        let toc_spec: [(f64, f64, f64); 6] = [
            (ty_size, 18.0, 0.0),
            (ty_size - 0.5, 16.0, 14.0),
            (ty_size - 1.0, 15.0, 28.0),
            (ty_size - 1.0, 14.0, 42.0),
            (ty_size - 1.0, 13.0, 56.0),
            (ty_size - 1.0, 13.0, 70.0),
        ];
        let mut toc_levels: Vec<PStyle> = Vec::new();
        for (idx, (sz, lead, indent)) in toc_spec.iter().enumerate() {
            let mut ts = PStyle::child(&body, &format!("T{}", idx + 1));
            ts.size = *sz;
            ts.leading = *lead;
            ts.left_indent = *indent;
            if idx == 0 {
                ts.color = hex_parse("#111111").unwrap();
            }
            toc_levels.push(ts);
        }
        let toc_title = PStyle {
            name: "TocTitle".to_string(),
            size: 18.0,
            leading: 18.0 * 1.2,
            space_after: 12.0,
            color: hex_parse("#111111").unwrap(),
            ..PStyle::child(&body, "TocTitle")
        };

        Styles { body, head, li, code, quote, code_flow, toc_levels, toc_title }
    }
}

/// `render(blocks, out_path, style, tmpdir, resolve, warns)` (`:217-462`).
///
/// Returns the `out_path` it wrote, like the authority returns `out_path`.
pub fn render(
    blocks: &Value,
    out_path: &str,
    style: &Value,
    tmpdir: &str,
    resolve: &dyn Fn(&str) -> Option<String>,
    warns: &mut Vec<String>,
) -> Result<String, PdfError> {
    let bytes = render_bytes(blocks, style, tmpdir, resolve, warns)?;
    let parent = std::path::Path::new(out_path).parent();
    if let Some(p) = parent {
        if !p.as_os_str().is_empty() && !p.exists() {
            let _ = std::fs::create_dir_all(p);
        }
    }
    std::fs::write(out_path, &bytes).map_err(|e| {
        PdfError::new(PdfErrorKind::Invalid, format!("PDF 写入失败: {out_path}: {e}"))
    })?;
    Ok(out_path.to_string())
}

/// The file-system-free half of [`render`]: the same document as PDF bytes.
pub fn render_bytes(
    blocks: &Value,
    style: &Value,
    tmpdir: &str,
    resolve: &dyn Fn(&str) -> Option<String>,
    warns: &mut Vec<String>,
) -> Result<Vec<u8>, PdfError> {
    let doc_ctx = build(blocks, style, tmpdir, resolve, warns)?;
    Ok(write_pdf(&doc_ctx))
}

