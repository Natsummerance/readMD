/// The code point -> WinAnsi code map the base-14 faces can actually use.
pub fn winansi_code(c: char) -> Option<u8> {
    let u = c as u32;
    if u >= 0x20 && u <= 0x7e {
        return Some(u as u8);
    }
    if u >= 0xa0 && u <= 0xff {
        return Some(u as u8);
    }
    if u > 0xffff {
        return None;
    }
    for i in 0x80..0x100usize {
        if WINANSI_UNICODE[i] == u as u16 {
            return Some(i as u8);
        }
    }
    None
}

