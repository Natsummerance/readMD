    #[test]
    fn paragraphs_break_only_at_spaces() {
        let style = style_for(json!({}));
        let st = Styles::build(&style, "MicrosoftYaHei");
        let word = "x".repeat(400);
        let runs = inline_markup(&Value::Array(txts(&word)), &style, "T:/tmp", &no_image);
        let lines = paragraph_lines(&runs, &st.body, 481.2);
        // 481.2 pt / (0.556 em * 11 pt) = 78 glyphs per hard-split line
        assert!(lines.len() >= 4, "{:?}", lines.iter().map(|l| l.text.len()).collect::<Vec<usize>>());
        assert_eq!(
            lines.iter().map(|l| l.text.as_str()).collect::<Vec<_>>().concat(),
            word,
            "a hard split must not swallow a single glyph"
        );
        assert!(lines.iter().all(|l| l.width <= 481.2 + 1e-6), "{:?}", lines.iter().map(|l| (l.text.chars().count(), l.width)).collect::<Vec<_>>());
        // `wordWrap` is left at its None default, so a line only breaks at a
        // space when one fits.
        let soft = paragraph_lines(&inline_markup(&Value::Array(txts("a b")), &style, "T:/tmp", &no_image),
                                   &st.body, 481.2);
        assert_eq!(soft.len(), 1);
        assert_eq!(soft[0].text, "a b");
    }

