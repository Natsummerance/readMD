/// PNG/JPEG/GIF header sniff — the native stand-in for
/// `reportlab.lib.utils.ImageReader(src).getSize()`.
pub fn image_size_bytes(data: &[u8]) -> Option<(f64, f64)> {
    if data.len() >= 24 && &data[0..8] == b"\x89PNG\r\n\x1a\n" && &data[12..16] == b"IHDR" {
        let w = u32::from_be_bytes([data[16], data[17], data[18], data[19]]) as f64;
        let h = u32::from_be_bytes([data[20], data[21], data[22], data[23]]) as f64;
        return Some((w, h));
    }
    if data.len() >= 4 && data[0] == 0xff && data[1] == 0xd8 {
        let mut i = 2usize;
        while i + 9 < data.len() {
            if data[i] != 0xff {
                i += 1;
                continue;
            }
            let marker = data[i + 1];
            let len = u16::from_be_bytes([data[i + 2], data[i + 3]]) as usize;
            let sof = matches!(marker, 0xc0..=0xc3 | 0xc5..=0xc7 | 0xc9..=0xcb | 0xcd..=0xcf);
            if sof {
                let h = u16::from_be_bytes([data[i + 5], data[i + 6]]) as f64;
                let w = u16::from_be_bytes([data[i + 7], data[i + 8]]) as f64;
                return Some((w, h));
            }
            if marker == 0xd8 || marker == 0x01 || (0xd0..=0xd9).contains(&marker) {
                i += 2;
            } else {
                i += 2 + len;
            }
        }
        return None;
    }
    if data.len() >= 10 && (&data[0..6] == b"GIF87a" || &data[0..6] == b"GIF89a") {
        let w = u16::from_le_bytes([data[6], data[7]]) as f64;
        let h = u16::from_le_bytes([data[8], data[9]]) as f64;
        return Some((w, h));
    }
    None
}

/// `ImageReader(src).getSize()` for a path already resolved to an absolute file.
pub fn image_size_path(src: &str) -> Option<(f64, f64)> {
    if src.starts_with("http://") || src.starts_with("https://") {
        return None;
    }
    let data = std::fs::read(src).ok()?;
    image_size_bytes(&data)
}

/// `_img_tag(tmpdir, data, width, height)` (`:120-128`) — write the PNG beside
/// the other inline assets and produce the tag's *geometry*.
pub fn img_tag(tmpdir: &str, data: Option<&[u8]>, width: f64, height: f64) -> Option<InlineImage> {
    let data = data?;
    if width == 0.0 {
        return None;
    }
    let name = format!("m_{}_.png", fnv_hex(data));
    let path = join_path(tmpdir, &name);
    if !std::path::Path::new(&path).exists() {
        let _ = std::fs::write(&path, data);
    }
    Some(InlineImage { src: path.replace('\\', "/"), width, height, math: None })
}

/// Stand-in for `abs(hash(data))`: only ever used to name a temp file, so the
/// value is unobservable.  Python's `hash` of `bytes` is SIPASH-randomised per
/// process anyway.
fn fnv_hex(data: &[u8]) -> u64 {
    let mut h: u64 = 0xcbf2_9ce4_8422_2325;
    for b in data {
        h ^= *b as u64;
        h = h.wrapping_mul(0x100_0000_01b3);
    }
    h
}

#[derive(Debug, Clone, PartialEq)]
pub struct InlineImage {
    pub src: String,
    pub width: f64,
    pub height: f64,
    /// A vector formula placed like an image (`src` is empty).  `height` is
    /// then height + depth; the formula's own baseline is used when drawing.
    pub math: Option<std::sync::Arc<crate::math_layout::Formula>>,
}

impl InlineImage {
    fn formula(f: crate::math_layout::Formula) -> InlineImage {
        InlineImage {
            src: String::new(),
            width: f.width,
            height: f.height + f.depth,
            math: Some(std::sync::Arc::new(f)),
        }
    }
}

