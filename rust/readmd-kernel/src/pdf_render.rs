//! `src/readmd_modules/mdexport/pdf_render.py` — native PDF renderer.
//!
//! Markdown block AST -> PDF.  The Python authority drives reportlab's
//! platypus flowable pipeline (see `review-9b-pdf-renderer-divergence.md`);
//! this module re-implements that pipeline natively: the same style tokens,
//! the same `mm` geometry, the same flowable set (`Paragraph`, `Spacer`,
//! `PageBreak`, `Table`/`TableStyle`, `Preformatted`, `Image`, `HRFlowable`,
//! `TableOfContents`), the same `BaseDocTemplate` page decoration
//! (`_ExportDoc._footer`) and the same heading -> TOC-entry / PDF-outline
//! notification (`_ExportDoc.afterFlowable`).
//!
//! Nothing here shells out, and nothing here imports Python: the document is
//! composed as PDF objects and written with `std::fs`.
//!
//! ## Deliberate representation changes
//! * `_inline_markup` returns a *reportlab markup string* (`<b>`, `<font>`,
//!   `<a>`, `<img>`).  A native renderer has no markup parser to feed that to,
//!   so [`inline_markup`] returns the styled run stream that the markup *means*
//!   (see [`Run`]).  Every property the markup would have carried — face,
//!   `max(6.0, code.size - 0.5)` code size, `#c7254e` code colour, the link
//!   colour taken from `HexColor(...).hexval()[2:]`, the
//!   `typography.size * 1.3` inline-image scale — is preserved on the run.
//!   [`inline_plain_text`] is the `Paragraph.getPlainText()` projection the
//!   TOC/outline path needs.
//! * Font faces: the CJK `TTFont` ladder (`MicrosoftYaHei`, `SimHei`, …) needs
//!   a TTF reader plus CIDFontType0/2 subsetting, which is not in this file's
//!   budget.  The renderer therefore emits the base-14 faces for every code
//!   WinAnsi can express and a non-embedded `STSong-Light` `/UniGB-UCS2-H`
//!   `Type0` font for the rest — exactly reportlab's own
//!   `UnicodeCIDFont('STSong-Light')` fallback rung (`pdf_render.py:76`).
//!   The *selection ladder* in [`register_fonts`] is ported verbatim, so the
//!   logical font name, the family mapping and the warning text are parity;
//!   only the glyph source differs.

