/// `register_fonts()` (`:38-83`).
///
/// The registration ladder is ported statement for statement: `msyh.ttc` ->
/// `NotoSansCJK-Regular.ttc` -> `PingFang.ttc`, the `MicrosoftYaHei-Bold`
/// family pairing behind its own `try`, the `simhei.ttf` fallback rung and the
/// `UnicodeCIDFont('STSong-Light')` / `Helvetica` last resort.  What differs is
/// only what "register" buys us: this kernel records the *name* and draws with
/// the faces in [`Face`] until a TTF subsetter exists.
pub fn register_fonts() -> String {
    if let Some(n) = registered_font_name() {
        if font_ready(&n) {
            return n;
        }
    }
    let regular = first_existing(&[
        "C:\\Windows\\Fonts\\msyh.ttc",
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
        "/System/Library/Fonts/PingFang.ttc",
    ]);
    let bold = first_existing(&[
        "C:\\Windows\\Fonts\\msyhbd.ttc",
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Bold.ttc",
        "/System/Library/Fonts/PingFang.ttc",
    ]);
    if std::path::Path::new(&regular).exists() {
        note_registered("MicrosoftYaHei");
        if std::path::Path::new(&bold).exists() {
            note_registered("MicrosoftYaHei-Bold");
        }
        set_registered_name("MicrosoftYaHei");
        return "MicrosoftYaHei".to_string();
    }
    let fallback = first_existing(&[
        "C:\\Windows\\Fonts\\simhei.ttf",
        "/usr/share/fonts/opentype/noto/NotoSansCJK-Regular.ttc",
    ]);
    if std::path::Path::new(&fallback).exists() {
        note_registered("SimHei");
        set_registered_name("SimHei");
        return "SimHei".to_string();
    }
    note_registered("STSong-Light");
    set_registered_name("STSong-Light");
    "STSong-Light".to_string()
}

fn set_registered_name(n: &str) {
    REGISTERED_NAME.with(|r| *r.borrow_mut() = Some(n.to_string()));
}

