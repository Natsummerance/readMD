# Check all json files in assets/i18n
all_langs = sorted([f[:-5] for f in os.listdir(I18N_DIR) if f.endswith(".json") and f != "meta.json"])
print("Found", len(all_langs), "languages.")

def get_localized_dict(lang_code):
    if lang_code in TRANSLATIONS:
        return TRANSLATIONS[lang_code]
    if lang_code in LANG_TRANSLATIONS:
        return LANG_TRANSLATIONS[lang_code]
    raise ValueError(f"Strict i18n audit (/dbs-slowisfast): Language '{lang_code}' missing from translations!")

updated_count = 0
for lang in all_langs:
    fpath = os.path.join(I18N_DIR, f"{lang}.json")
    with open(fpath, "r", encoding="utf-8") as f:
        data = json.load(f)

    loc = get_localized_dict(lang)
    for k, v in loc.items():
        data[k] = v

    # Write back cleanly formatted JSON with 2-space indentation
    with open(fpath, "w", encoding="utf-8") as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    updated_count += 1

print(f"Successfully audited and updated {updated_count} language dictionaries.")
