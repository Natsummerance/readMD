def main():
    meta_path = os.path.join(I18N_DIR, "meta.json")
    with open(meta_path, "r", encoding="utf-8") as f:
        meta = json.load(f)

    all_locales = sorted(list(meta.keys()))
    print(f"Auditing {len(all_locales)} languages for full i18n localization...")

    missing_locales = [loc for loc in all_locales if loc not in PLUGIN_TRANSLATIONS]
    if missing_locales:
        raise ValueError(f"CRITICAL: Missing translations for locales: {missing_locales}")

    expected_keys = list(PLUGIN_TRANSLATIONS["en"].keys())
    print(f"Validating {len(expected_keys)} keys across all {len(all_locales)} languages...")

    updated_count = 0
    for locale in all_locales:
        fpath = os.path.join(I18N_DIR, f"{locale}.json")
        if not os.path.exists(fpath):
            raise FileNotFoundError(f"Missing locale JSON: {fpath}")

        with open(fpath, "r", encoding="utf-8") as f:
            data = json.load(f)

        loc_dict = PLUGIN_TRANSLATIONS[locale]
        # Verify all expected keys are present in translation dictionary
        for k in expected_keys:
            if k not in loc_dict:
                raise KeyError(f"Locale '{locale}' is missing key '{k}' in translation dictionary!")
            val = loc_dict[k]
            if not val or not val.strip():
                raise ValueError(f"Locale '{locale}' has empty translation for key '{k}'!")
            # Ensure placeholders {name} and {other} are preserved
            if "{name}" in k or "switchedMutual" in k:
                if "{name}" not in val or "{other}" not in val:
                    raise ValueError(f"Locale '{locale}' lost placeholder tokens in '{k}': {val}")
            data[k] = val

        with open(fpath, "w", encoding="utf-8") as f:
            json.dump(data, f, ensure_ascii=False, indent=2)
            f.write("\n")
        updated_count += 1

    print(f"Successfully localized {len(expected_keys)} keys across all {updated_count} languages!")


if __name__ == "__main__":
    main()
